#define OUI_TABLE_SIZE ((int)(sizeof(OUI_TABLE)/sizeof(OUI_TABLE[0])))

/**
 * @brief Búsqueda binaria del OUI en la tabla.
 * @param mac  Dirección MAC de 6 bytes (solo se usan los 3 primeros)
 * @return     Nombre del fabricante o "Unknown"
 */
static inline const char *oui_vendor(const uint8_t *mac) {
    int lo = 0, hi = OUI_TABLE_SIZE - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        int cmp = memcmp(OUI_TABLE[mid].oui, mac, 3);
        if (cmp == 0) return OUI_TABLE[mid].vendor;
        if (cmp < 0)  lo = mid + 1;
        else          hi = mid - 1;
    }
    return "Unknown";
}
